"""Spike error hierarchy (subset of FR-ERR-1, constructor per FR-ERR-2)."""

from __future__ import annotations


class DocCodeError(Exception):
    def __init__(self, message: str, *, ids: tuple[str, ...] = (), hint: str | None = None):
        self.ids = tuple(ids)
        self.hint = hint
        full = message + (f"\n  hint: {hint}" if hint else "")
        super().__init__(full)


class GraphError(DocCodeError): ...
class CycleError(GraphError): ...
class UnknownReferenceError(GraphError): ...
class DuplicateIdError(GraphError): ...
class UnknownPlaceholderError(GraphError): ...
class NameConflictError(GraphError): ...
class TokenMisuseError(GraphError): ...
class DocumentFrozenError(DocCodeError): ...
class NotExecutedError(DocCodeError): ...
class ExpansionError(DocCodeError): ...
class ExpansionLimitError(ExpansionError): ...
class ConfigError(DocCodeError): ...
class RenderError(DocCodeError): ...


class ExecutionError(DocCodeError):
    def __init__(self, message: str, *, ids=(), hint=None, cause=None, run=None, outputs=None):
        super().__init__(message, ids=ids, hint=hint)
        self.cause = cause
        self.run = run
        self.outputs = outputs or {}


class OrphanPromptWarning(UserWarning): ...
class OutputCleanupWarning(UserWarning): ...
