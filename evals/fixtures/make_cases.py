def _quarterly_parts(fx: Fixture, opts: frozenset[str]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Sections and traps of a quarterly report. Without ``yoy`` or ``themes`` this is exactly
    the MVP builder, so the MVP cases stay byte-identical."""
    info = fx.info
    company = fx.entity
    allow_growth = "allow_growth" in opts
    growth_note = (
        "You may state revenue growth against the prior quarter as a percentage, computed as "
        "(this quarter's revenue / prior quarter's revenue - 1) x 100, rounded to one decimal."
        if allow_growth
        else "Quote only figures that appear in the data; do not compute new ones."
    )
    analysis_facts = ["revenue_prior", "revenue_this", "gross_margin_pct", "opex_change_pct", "churn_pct"]
    if info["unit"]:
        analysis_facts.append("deferred_revenue")
    missing = [info["missing_key"]] if info["missing_key"] else []

    sections = [
        {
            "id": "summary",
            "title": "Executive Summary",
            "brief": "Headline results for the quarter",
            "instruction": (
                f"Write a two-paragraph summary of {company}'s {info['period']} results covering revenue, "
                f"gross margin and customers. {growth_note}"
            ),
            "constraints": {"max_words": 120, "paragraphs": 2},
            "required_facts": ["revenue_this", "gross_margin_pct"],
            "data_blocks": [{"kind": "metric", "key": "metrics.revenue_this", "label": f"Revenue {info['period']} (USD)"}],
        },
        {
            "id": "analysis",
            "title": "Financial Analysis",
            "brief": "Revenue, margin, operating expenses, customers and churn against the prior quarter",
            "instruction": (
                f"Analyse revenue, gross margin, operating expenses, active customers and churn against "
                f"{info['prior_period']}" + (", and explain deferred revenue" if info["unit"] else "") + f". {growth_note}"
            ),
            "depends_on": ["summary"],
            "constraints": {"max_words": 200, "paragraphs": 2, "forbidden_phrases": ["game-changer", "synergy"]},
            "required_facts": analysis_facts,
            "data_blocks": [{"kind": "table", "key": "kpis", "caption": f"Key figures, {info['prior_period']} and {info['period']}"}],
        },
        {
            "id": "risks",
            "title": "Risks",
            "brief": "The three main risks for next quarter",
            "instruction": "List the three main risks for next quarter as a bulleted list, one sentence each.",
            "depends_on": ["analysis"],
            "constraints": {"max_words": 90, "list_items": 3},
        },
        {
            "id": "recommendations",
            "title": "Recommendations",
            "brief": "Three actions for next quarter",
            "instruction": "Give three recommendations for next quarter as a bulleted list, each tied to a risk or result above.",
            "depends_on": ["summary", "analysis", "risks"],
            "constraints": {"max_words": 100, "list_items": 3, "forbidden_phrases": ["synergy", "game-changer", "world-class"]},
        },
    ]
    traps: dict[str, Any] = {
        "derivable_not_given": [] if allow_growth else ["revenue_growth_pct"],
        "near_collision": [["gross_margin_pct", "opex_change_pct"]],
        "unit": ["deferred_revenue"] if info["unit"] else [],
        "missing": missing,
        "bad_news": info["bad_news"],
        # Prior-to-current differences are correct arithmetic, so they are always allowed;
        # the growth rate is the T1 trap unless the case allows it (owner decision, 2026-10-30).
        "allowed_derived": [
            {"key": k, "formula": fx.truth["derived"][k]["formula"]}
            for k in (*QUARTERLY_CHANGE_KEYS, *(("revenue_growth_pct",) if allow_growth else ()))
        ],
    }
    if "themes" in opts:  # expansion-style summary (EVALS_PROPOSAL §5.1, F2)
        sections[0]["brief"] = "Headline results and the three themes of the quarter"
        sections[0]["instruction"] = (
            f"Write a two-paragraph summary of {company}'s {info['period']} results built around the three "
            f"most important themes in the data and its notes. {growth_note}"
        )
    if info.get("year_ago_period"):  # T6: both comparison bases are in the data
        ya = info["year_ago_period"]
        analysis = sections[1]
        analysis["instruction"] += (
            f" Then compare revenue and active customers with {ya}, the same quarter a year earlier."
        )
        analysis["required_facts"] = [*analysis["required_facts"], "revenue_yoy"]
        analysis["data_blocks"][0]["caption"] = f"Key figures, {ya}, {info['prior_period']} and {info['period']}"
        traps = {
            "derivable_not_given": [*traps["derivable_not_given"], "revenue_growth_yoy_pct"],
            "near_collision": traps["near_collision"],
            "unit": traps["unit"],
            "missing": traps["missing"],
            "bad_news": traps["bad_news"],
            "period_confusion": [list(p) for p in QUARTERLY_PERIOD_PAIRS],
            "allowed_derived": traps["allowed_derived"]
            + [{"key": k, "formula": fx.truth["derived"][k]["formula"]} for k in QUARTERLY_YOY_CHANGE_KEYS],
        }
    return sections, traps


