def read_seeds(path: Path = SEEDS_PATH) -> list[tuple[str, int, frozenset[str]]]:
    out = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        family, seed, *rest = line.split()
        opts = frozenset(o for o in (rest[0] if rest else "-").split(",") if o and o != "-")
        out.append((family, int(seed), opts))
    return out


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# ---------------------------------------------------------------- TOML writer (just what case.toml needs)


def _toml_value(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{_toml_key(k)} = {_toml_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(f"cannot write {type(v).__name__} to TOML")


def _toml_key(k: str) -> str:
    return k if re.fullmatch(r"[A-Za-z0-9_-]+", k) else json.dumps(k)


def to_toml(case: dict[str, Any]) -> str:
    lines = [HEADER.rstrip("\n")]
    for k, v in case.items():
        if k not in ("sections", "traps", "attachments"):
            lines.append(f"{_toml_key(k)} = {_toml_value(v)}")
    for s in case["sections"]:
        lines += ["", "[[sections]]"]
        lines += [f"{_toml_key(k)} = {_toml_value(v)}" for k, v in s.items()]
    lines += ["", "[traps]"]
    lines += [f"{_toml_key(k)} = {_toml_value(v)}" for k, v in case["traps"].items()]
    if case.get("attachments"):
        lines += ["", "[attachments]"]
        lines += [f"{_toml_key(k)} = {_toml_value(v)}" for k, v in case["attachments"].items()]
    return "\n".join(lines) + "\n"


